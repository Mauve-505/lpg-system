export function makeT(lang) {
  const table = STRINGS[lang] || STRINGS.en
  return (key, fallback = '') => table[key] ?? STRINGS.en[key] ?? fallback ?? key
}

export function readLang() {
  try {
    const saved = localStorage.getItem('lpg.lang')
    return LANGUAGES.some(l => l.code === saved) ? saved : 'en'
  } catch {
    return 'en'
  }
}

export function saveLang(lang) {
  try { localStorage.setItem('lpg.lang', lang) } catch { /* ignore */ }
}
